const READ_ONLY_GIT_SUBCOMMANDS: &[&str] = &[
    "status",
    "diff",
    "log",
    "show",
    "rev-parse",
    "ls-files",
    "describe",
    "branch",
];

fn is_builtin_intrinsically_read_only(cmd_name: &str, command: &str) -> bool {
    if INTRINSICALLY_READ_ONLY_COMMANDS.contains(&cmd_name) {
        return true;
    }

    if cmd_name == "git" {
        let subcommand = command.split_whitespace().nth(1).unwrap_or("");
        return READ_ONLY_GIT_SUBCOMMANDS.contains(&subcommand)
            && !command.split_whitespace().any(|token| {
                matches!(
                    token,
                    "-d" | "-D" | "-m" | "-M" | "-f" | "--delete" | "--force"
                )
            });
    }

    false
}

/// Shell execution policy loaded from `shell-policy.toml`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ShellPolicy {
    /// Commands that are considered read-only and may bypass approval.
    pub read_only_commands: Vec<String>,
    /// Patterns that, when present in a command, block auto-approval even if
    /// the base command is in `read_only_commands`.
    pub write_patterns: Vec<String>,
}

impl Default for ShellPolicy {
    fn default() -> Self {
        Self {
            read_only_commands: DEFAULT_READ_ONLY_COMMANDS
                .iter()
                .map(|s| s.to_string())
                .collect(),
            write_patterns: DEFAULT_WRITE_PATTERNS
                .iter()
                .map(|s| s.to_string())
                .collect(),
        }
    }
}

impl ShellPolicy {
    /// Load from `path`.  If the file does not exist, create it with the built-in
    /// defaults and return the default policy.
    pub fn load(path: &Path) -> Self {
        if path.exists() {
            match std::fs::read_to_string(path) {
                Ok(content) => match toml::from_str::<ShellPolicy>(&content) {
                    Ok(policy) => {
                        tracing::info!(
                            read_only = policy.read_only_commands.len(),
                            write_patterns = policy.write_patterns.len(),
                            path = %path.display(),
                            "Loaded shell policy"
                        );
                        return policy;
                    }
                    Err(e) => {
                        tracing::warn!(error = %e, path = %path.display(), "Invalid shell-policy.toml — using defaults");
                    }
                },
                Err(e) => {
                    tracing::warn!(error = %e, path = %path.display(), "Cannot read shell-policy.toml — using defaults");
                }
            }
        }
        let policy = ShellPolicy::default();
        if let Err(e) = policy.save(path) {
            tracing::warn!(error = %e, path = %path.display(), "Failed to write default shell-policy.toml");
        }
        policy
    }

    /// Persist to `path`.
    pub fn save(&self, path: &Path) -> Result<(), String> {
        let content = toml::to_string_pretty(self).map_err(|e| e.to_string())?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        std::fs::write(path, content).map_err(|e| e.to_string())
    }

    /// Check whether `command` is a known read-only operation.
    ///
    /// 1. Reject any command containing shell metacharacters.
    /// 2. Extract the first whitespace-separated word (the command name).
    /// 3. Strip any leading path (e.g. /bin/ls → ls).
    /// 4. Check against `read_only_commands`.
    /// 5. Guard against known write subcommands via `write_patterns`.
    pub fn is_read_only(&self, command: &str) -> bool {
        const DANGEROUS_CHARS: &[char] = &[
            ';', '|', '&', '`', '$', '(', ')', '<', '>', '*', '?', '{', '}', '[', ']', '\\', '!',
        ];
        if command.chars().any(|c| DANGEROUS_CHARS.contains(&c)) {
            return false;
        }

        let first_word = command.split_whitespace().next().unwrap_or("");
        if first_word.is_empty() {
            return false;
        }

        let cmd_name = std::path::Path::new(first_word)
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or(first_word);

        let listed = self.read_only_commands.iter().any(|c| c == cmd_name);
        if !listed {
            return false;
        }

        let lower = command.to_ascii_lowercase();
        if self.write_patterns.iter().any(|p| lower.contains(p)) {
            return false;
        }

        is_builtin_intrinsically_read_only(cmd_name, command)
            || !DEFAULT_READ_ONLY_COMMANDS.contains(&cmd_name)
    }

    /// Add a command to the read-only allowlist.
    pub fn add_read_only(&mut self, cmd: &str) {
        let cmd = cmd.trim().to_string();
        if !self.read_only_commands.contains(&cmd) {
            self.read_only_commands.push(cmd);
        }
    }

    /// Remove a command from the read-only allowlist.
    pub fn remove_read_only(&mut self, cmd: &str) {
        let cmd = cmd.trim().to_string();
        self.read_only_commands.retain(|c| c != &cmd);
    }

    /// Add a write-pattern guard.
    pub fn add_write_pattern(&mut self, pattern: &str) {
        let pattern = pattern.trim().to_ascii_lowercase();
        if !self.write_patterns.contains(&pattern) {
            self.write_patterns.push(pattern);
        }
    }

    /// Remove a write-pattern guard.
    pub fn remove_write_pattern(&mut self, pattern: &str) {
        let pattern = pattern.trim().to_ascii_lowercase();
        self.write_patterns.retain(|p| p != &pattern);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_is_read_only() {
        let policy = ShellPolicy::default();
        assert!(policy.is_read_only("ls"));
        assert!(policy.is_read_only("cat /etc/passwd"));
        assert!(policy.is_read_only("/usr/bin/git status"));
        assert!(policy.is_read_only("git show HEAD"));
        assert!(!policy.is_read_only("rm -rf /"));
        assert!(!policy.is_read_only("ls; rm -rf /"));
        assert!(!policy.is_read_only("git push origin main"));
        assert!(!policy.is_read_only("git branch -D feature"));
        assert!(!policy.is_read_only("cargo test --workspace"));
        assert!(!policy.is_read_only("python scripts/update_state.py"));
        assert!(!policy.is_read_only("sed -i s/a/b/g Cargo.toml"));
        assert!(!policy.is_read_only("docker ps"));
    }

    #[test]
    fn test_add_remove_read_only() {
        let mut policy = ShellPolicy::default();
        policy.add_read_only("mycmd");
        assert!(policy.is_read_only("mycmd"));
        policy.remove_read_only("mycmd");
        assert!(!policy.is_read_only("mycmd"));
    }

    #[test]
    fn test_add_remove_write_pattern() {
        let mut policy = ShellPolicy::default();
        policy.add_read_only("mycmd");
        policy.add_write_pattern("mycmd write");
        assert!(!policy.is_read_only("mycmd write"));
        policy.remove_write_pattern("mycmd write");
        assert!(policy.is_read_only("mycmd"));
    }

    #[test]
    fn test_save_and_load_roundtrip() {
        let mut policy = ShellPolicy::default();
        policy.add_read_only("custom_tool");
        policy.add_write_pattern("custom_tool destroy");

        let tmp = std::env::temp_dir().join("test-shell-policy.toml");
        policy.save(&tmp).unwrap();

        let loaded = ShellPolicy::load(&tmp);
        assert!(loaded.is_read_only("custom_tool"));
        assert!(!loaded.is_read_only("custom_tool destroy"));
        std::fs::remove_file(&tmp).unwrap();
    }

    #[test]
    fn test_load_creates_defaults_when_missing() {
        let tmp = std::env::temp_dir().join("test-shell-policy-missing.toml");
        if tmp.exists() {
            std::fs::remove_file(&tmp).unwrap();
        }
        let policy = ShellPolicy::load(&tmp);
        assert!(policy.is_read_only("ls"));
        assert!(policy.is_read_only("cat"));
        std::fs::remove_file(&tmp).unwrap();
    }
}
